package strip

import (
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

func TestLines(t *testing.T) {
	tests := []struct {
		name, src, want string
		removed         int
	}{
		{
			name: "annotations above a func",
			src:  "package a\n\n// f does things.\n// @Summary F\n//@Router /f [get]\nfunc f() {}\n",
			want: "package a\n\n// f does things.\nfunc f() {}\n", removed: 2,
		},
		{
			name: "indented and last line without newline",
			src:  "package a\n\t// @title X\n// @version 1",
			want: "package a\n", removed: 2,
		},
		{
			name: "trailing comment after code is kept",
			src:  "package a\n\nvar x = 1 // @not an annotation line\n",
			want: "package a\n\nvar x = 1 // @not an annotation line\n",
		},
		{
			name: "text in strings and block comments is kept",
			src:  "package a\n\nvar s = `\n// @Summary in a raw string\n`\n\n/*\n// @Summary in a block comment\n*/\n",
			want: "package a\n\nvar s = `\n// @Summary in a raw string\n`\n\n/*\n// @Summary in a block comment\n*/\n",
		},
		{
			name: "other comments are kept",
			src:  "package a\n\n//go:generate x\n// plain @ comment\n// @\nfunc f() {}\n",
			want: "package a\n\n//go:generate x\n// plain @ comment\nfunc f() {}\n", removed: 1,
		},
		{
			name: "CRLF",
			src:  "package a\r\n// @Summary F\r\nfunc f() {}\r\n",
			want: "package a\r\nfunc f() {}\r\n", removed: 1,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, n, err := Lines("a.go", []byte(tt.src))
			if err != nil {
				t.Fatal(err)
			}
			if string(got) != tt.want || n != tt.removed {
				t.Errorf("Lines() = %q, %d; want %q, %d", got, n, tt.want, tt.removed)
			}
		})
	}
}

func TestRun(t *testing.T) {
	dir := t.TempDir()
	write := func(rel, content string) {
		t.Helper()
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("cmd/server/main.go", "package main\n\n// @title X\nfunc main() {}\n")
	write("internal/a/a.go", "package a\n")
	write(".git/hooks/x.go", "// @kept because .git is skipped\n")
	write("internal/apispec/swagger.json", "{}")
	write("internal/apispec/swagger.yaml", "{}")
	write("internal/apispec/apispec.go", "package apispec\n")

	res, err := Run(dir)
	if err != nil {
		t.Fatal(err)
	}
	want := Result{Files: 1, Lines: 1, Deleted: []string{"internal/apispec/swagger.json", "internal/apispec/swagger.yaml"}}
	if !reflect.DeepEqual(res, want) {
		t.Errorf("Run() = %+v, want %+v", res, want)
	}
	if b, _ := os.ReadFile(filepath.Join(dir, "cmd/server/main.go")); string(b) != "package main\n\nfunc main() {}\n" {
		t.Errorf("main.go = %q", b)
	}
	if _, err := os.Stat(filepath.Join(dir, "internal/apispec/apispec.go")); err != nil {
		t.Errorf("hand-written apispec.go was removed: %v", err)
	}

	// A second run finds nothing to do.
	res, err = Run(dir)
	if err != nil {
		t.Fatal(err)
	}
	if res.Files != 0 || res.Lines != 0 || len(res.Deleted) != 0 {
		t.Errorf("second Run() = %+v, want nothing removed", res)
	}
}

func TestRunDeletesOnlyGeneratedDocsGo(t *testing.T) {
	for _, tt := range []struct {
		content string
		deleted bool
	}{
		{"// Code generated by swaggo/swag. DO NOT EDIT.\npackage apispec\n", true},
		{"package apispec\n", false},
	} {
		dir := t.TempDir()
		path := filepath.Join(dir, "internal", "apispec", "docs.go")
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(tt.content), 0o644); err != nil {
			t.Fatal(err)
		}
		if _, err := Run(dir); err != nil {
			t.Fatal(err)
		}
		_, err := os.Stat(path)
		if deleted := os.IsNotExist(err); deleted != tt.deleted {
			t.Errorf("docs.go %q: deleted = %v, want %v", tt.content, deleted, tt.deleted)
		}
	}
}
