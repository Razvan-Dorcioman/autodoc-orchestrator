package specroute

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestCheckExisting(t *testing.T) {
	write := func(dir, rel, content string) {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	const main = "package main\n\nimport \"net/http\"\n\nfunc main() { http.ListenAndServe(\":8080\", nil) }\n"

	for _, tt := range []struct {
		name  string
		files map[string]string
		want  string // "" for no error
	}{
		{"plain service", map[string]string{"main.go": main, "config.json": `{"port": 8080}`, "deploy.yaml": "kind: Deployment\n"}, ""},
		{"earlier autodoc run", map[string]string{
			"main.go":                       main,
			"internal/apispec/apispec.go":   source,
			"internal/apispec/swagger.json": `{"swagger": "2.0"}`,
			"internal/apispec/swagger.yaml": "swagger: \"2.0\"\n",
		}, ""},
		{"swag output in its own spec dir", map[string]string{"internal/apispec/docs.go": "// Code generated by swaggo/swag. DO NOT EDIT.\npackage apispec\n\nimport \"github.com/swaggo/swag\"\n"}, ""},
		{"specs in testdata and vendor", map[string]string{"testdata/openapi.yaml": "openapi: 3.1.0\n", "vendor/x/swagger.json": `{"swagger": "2.0"}`}, ""},
		{"swag default output", map[string]string{"docs/docs.go": "// Code generated by swaggo/swag. DO NOT EDIT.\npackage docs\n", "docs/swagger.json": `{"swagger": "2.0", "info": {}}`}, "docs/docs.go: generated by swag"},
		{"swagger json", map[string]string{"docs/swagger.json": `{"swagger": "2.0", "info": {}}`}, "docs/swagger.json: Swagger 2.0 document"},
		{"unquoted swagger yaml", map[string]string{"api/spec.yml": "swagger: 2.0\ninfo: {}\n"}, "api/spec.yml: Swagger 2.0 document"},
		{"hand-written openapi", map[string]string{"api/catalog.yaml": "openapi: 3.0.3\ninfo:\n  title: Catalog\n"}, "api/catalog.yaml: OpenAPI 3.0.3 document"},
		{"http-swagger", map[string]string{"main.go": "package main\n\nimport (\n\t\"net/http\"\n\n\thttpSwagger \"github.com/swaggo/http-swagger/v2\"\n)\n"}, "main.go: imports github.com/swaggo/http-swagger/v2"},
	} {
		dir := t.TempDir()
		for rel, content := range tt.files {
			write(dir, rel, content)
		}
		err := CheckExisting(dir)
		switch {
		case tt.want == "" && err != nil:
			t.Errorf("%s: err = %v, want none", tt.name, err)
		case tt.want != "" && (err == nil || !strings.Contains(err.Error(), tt.want)):
			t.Errorf("%s: err = %v, want one containing %q", tt.name, err, tt.want)
		}
	}
}
