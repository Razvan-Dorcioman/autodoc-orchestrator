package specroute

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"

	"autodoc/internal/strip"
)

// swaggoPrefix is the import path prefix of swag's runtime and its UI
// handlers (http-swagger, gin-swagger, echo-swagger).
const swaggoPrefix = "github.com/swaggo/"

// maxSpecSize bounds the JSON and YAML files read to tell whether they are a
// spec; a larger one is not read.
const maxSpecSize = 10 << 20

// CheckExisting fails when the working copy at dir already has an API spec
// outside SpecDir: a Swagger or OpenAPI document, swag's generated docs.go,
// or an import of swag or one of its UI handlers. A run rewrites the
// annotations and generates its own spec in SpecDir, so such a spec would go
// stale next to it, or be served from a second endpoint. SpecDir itself is
// strip's and checkSpecDir's: a spec there is regenerated.
func CheckExisting(dir string) error {
	var found []string
	fset := token.NewFileSet()
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(dir, path)
		rel = filepath.ToSlash(rel)
		if d.IsDir() {
			switch {
			case d.Name() == ".git", d.Name() == "vendor", d.Name() == "testdata", d.Name() == "node_modules", rel == strip.SpecDir:
				return filepath.SkipDir
			}
			return nil
		}
		switch filepath.Ext(path) {
		case ".go":
			src, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if bytes.Contains(src, []byte("Code generated by swaggo/swag")) {
				found = append(found, rel+": generated by swag")
				return nil
			}
			file, err := parser.ParseFile(fset, path, src, parser.ImportsOnly)
			if err != nil {
				return nil // not ours to report; the build and facts steps see it
			}
			for _, imp := range file.Imports {
				if p, _ := strconv.Unquote(imp.Path.Value); strings.HasPrefix(p, swaggoPrefix) {
					found = append(found, rel+": imports "+p)
				}
			}
		case ".json", ".yaml", ".yml":
			if kind := specKind(path); kind != "" {
				found = append(found, rel+": "+kind+" document")
			}
		}
		return nil
	})
	if err != nil {
		return err
	}
	if len(found) == 0 {
		return nil
	}
	const show = 10
	list := found[:min(show, len(found))]
	msg := "- " + strings.Join(list, "\n- ")
	if len(found) > show {
		msg += fmt.Sprintf("\n- and %d more", len(found)-show)
	}
	return fmt.Errorf("the repo already has an API spec outside %s/; a run would generate a second one next to it, and the first would go stale:\n%s", strip.SpecDir, msg)
}

// specKind returns "Swagger 2.0" or "OpenAPI 3.x.y" when the file at path is
// a spec, by its top-level swagger or openapi key; else "".
func specKind(path string) string {
	if st, err := os.Stat(path); err != nil || st.Size() > maxSpecSize {
		return ""
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return ""
	}
	top := map[string]string{}
	if filepath.Ext(path) == ".json" {
		var m map[string]json.RawMessage
		if json.Unmarshal(data, &m) != nil {
			return ""
		}
		for _, k := range []string{"swagger", "openapi"} {
			var s string
			if raw, ok := m[k]; ok && json.Unmarshal(raw, &s) == nil {
				top[k] = s
			}
		}
	} else {
		// A node, not a map, so an unquoted `swagger: 2.0` keeps its text.
		var doc yaml.Node
		if yaml.Unmarshal(data, &doc) != nil || len(doc.Content) == 0 || doc.Content[0].Kind != yaml.MappingNode {
			return ""
		}
		m := doc.Content[0].Content
		for i := 0; i+1 < len(m); i += 2 {
			if k := m[i].Value; (k == "swagger" || k == "openapi") && m[i+1].Kind == yaml.ScalarNode {
				top[k] = m[i+1].Value
			}
		}
	}
	switch {
	case strings.HasPrefix(top["swagger"], "2."):
		return "Swagger " + top["swagger"]
	case strings.HasPrefix(top["openapi"], "3."):
		return "OpenAPI " + top["openapi"]
	}
	return ""
}
