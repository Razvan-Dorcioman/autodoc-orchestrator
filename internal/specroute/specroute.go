// Package specroute adds the one route a run may add to the service: GET
// /openapi.json, serving the generated spec from a small package that
// go:embeds it. The edit is a template, not model output: the same bytes on
// every run, and a no-op where the route is already registered.
package specroute

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"autodoc/internal/gofacts"
	"autodoc/internal/strip"
)

const (
	// Pattern is the ServeMux pattern of the added route.
	Pattern = "GET /openapi.json"
	// File is the package that embeds and serves the spec, next to swag's output.
	File = strip.SpecDir + "/apispec.go"

	pkgName = "apispec"
	handler = pkgName + ".Handler()" // the handler as facts.json writes it
	header  = "// Code generated by autodoc. DO NOT EDIT."
)

// source is the content of File. It needs only the standard library, and
// embeds the swagger.json swag writes next to it, so the spec reaches every
// build and image that compiles the service.
const source = header + `

// Package apispec serves the service's OpenAPI (Swagger 2.0) document,
// generated by swag from the annotations on the handlers.
package apispec

import (
	_ "embed"
	"net/http"
)

//go:embed swagger.json
var spec []byte

// Handler serves the OpenAPI document as JSON.
func Handler() http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write(spec)
	})
}
`

// Plan says where the route goes: next to the service's own registrations.
type Plan struct {
	File   string `json:"file"`   // slash path of the file that registers the routes
	Func   string `json:"func"`   // the function that registers them, e.g. "NewRouter" or "(*Server).routes"
	Mux    string `json:"mux"`    // what they are registered on, e.g. "mux", "s.mux", or "http" for the default mux
	Import string `json:"import"` // import path of the spec package
}

func (p Plan) String() string {
	return fmt.Sprintf("%s on %s in %s (%s)", Pattern, p.Mux, p.File, p.Func)
}

// Own reports whether a route from facts.json is the one this package adds,
// as a working copy that already went through a run registers it.
func Own(r gofacts.Route) bool { return r.Pattern == Pattern && r.Handler == handler }

// PlanFor decides where the route goes in the working copy at dir, before
// anything changes, so a service the template cannot handle fails before
// the agents run. The service's routes must be registered in one function,
// on one mux, and none may already answer GET /openapi.json.
func PlanFor(dir string, f *gofacts.Facts) (Plan, error) {
	p := Plan{Import: f.Module + "/" + strip.SpecDir}
	if err := checkSpecDir(dir); err != nil {
		return p, err
	}
	lines := map[string][]int{} // file -> lines of its registrations
	for _, r := range f.Routes {
		if Own(r) {
			continue
		}
		if r.Path == "/openapi.json" && (r.Method == "" || r.Method == "GET") {
			return p, fmt.Errorf("the service already serves %q at %s; the spec route would replace it", r.Pattern, r.Registered)
		}
		file, l, _ := strings.Cut(r.Registered, ":")
		n, err := strconv.Atoi(l)
		if err != nil {
			return p, fmt.Errorf("route %q: bad position %q", r.Pattern, r.Registered)
		}
		lines[file] = append(lines[file], n)
	}
	switch files := sortedKeys(lines); len(files) {
	case 0:
		return p, errors.New("the service registers no route with a constant pattern, so there is nowhere to add " + Pattern)
	case 1:
		p.File = files[0]
	default:
		return p, fmt.Errorf("routes are registered in several files (%s); the spec route goes next to them, so they must be in one", strings.Join(files, ", "))
	}

	src, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(p.File)))
	if err != nil {
		return p, err
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, p.File, src, parser.SkipObjectResolution)
	if err != nil {
		return p, err
	}
	want := map[int]bool{}
	for _, l := range lines[p.File] {
		want[l] = true
	}
	sites := map[string]bool{} // "func\x00mux" of every registration facts found
	for _, d := range file.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Body == nil {
			continue
		}
		ast.Inspect(fd.Body, func(n ast.Node) bool {
			call, ok := n.(*ast.CallExpr)
			if !ok || !want[fset.Position(call.Pos()).Line] {
				return true
			}
			if mux, ok := registration(call); ok {
				sites[gofacts.FuncName(fd)+"\x00"+mux] = true
			}
			return true
		})
	}
	switch keys := sortedKeys(sites); len(keys) {
	case 0:
		return p, fmt.Errorf("%s: the route registrations facts.json lists are not inside a function", p.File)
	case 1:
		p.Func, p.Mux, _ = strings.Cut(keys[0], "\x00")
	default:
		var where []string
		for _, k := range keys {
			fn, mux, _ := strings.Cut(k, "\x00")
			where = append(where, mux+" in "+fn)
		}
		return p, fmt.Errorf("%s registers routes on more than one mux or in more than one function (%s); the spec route goes next to them, so there must be one", p.File, strings.Join(where, ", "))
	}
	return p, nil
}

// Apply writes File and registers the route as p says. It is idempotent.
func Apply(dir string, p Plan) error {
	if err := checkSpecDir(dir); err != nil {
		return err
	}
	specFile := filepath.Join(dir, filepath.FromSlash(File))
	if err := os.MkdirAll(filepath.Dir(specFile), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(specFile, []byte(source), 0o644); err != nil {
		return err
	}
	path := filepath.Join(dir, filepath.FromSlash(p.File))
	src, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	out, err := Insert(src, p)
	if err != nil || bytes.Equal(out, src) {
		return err
	}
	return os.WriteFile(path, out, 0o644)
}

// checkSpecDir fails when SpecDir holds Go code other than File or swag's
// docs.go (which strip removes): the spec package needs the directory to
// itself.
func checkSpecDir(dir string) error {
	entries, err := os.ReadDir(filepath.Join(dir, filepath.FromSlash(strip.SpecDir)))
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		rel := strip.SpecDir + "/" + e.Name()
		data, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(rel)))
		if err != nil {
			return err
		}
		ours := rel == File && bytes.HasPrefix(data, []byte(header))
		swags := e.Name() == "docs.go" && bytes.Contains(data, []byte("Code generated by swaggo/swag"))
		if !ours && !swags {
			return fmt.Errorf("%s is not generated by autodoc or swag: %s/ must hold only the spec package", rel, strip.SpecDir)
		}
	}
	return nil
}

// Insert returns src, the content of p.File, with the spec route registered
// right after the last registration statement in p.Func, at its indentation,
// and the spec package imported. Nothing else changes, so the file keeps its
// layout and comments. It returns src unchanged when both are already there.
func Insert(src []byte, p Plan) ([]byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, p.File, src, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	tf := fset.File(file.Pos())
	nl := "\n"
	if bytes.Contains(src, []byte("\r\n")) {
		nl = "\r\n"
	}

	name, imported, err := importName(file, p.Import)
	if err != nil {
		return nil, err
	}
	var fd *ast.FuncDecl
	for _, d := range file.Decls {
		if f, ok := d.(*ast.FuncDecl); ok && f.Body != nil && gofacts.FuncName(f) == p.Func {
			fd = f
		}
	}
	if fd == nil {
		return nil, fmt.Errorf("%s: no func %s", p.File, p.Func)
	}
	present := false
	ast.Inspect(fd.Body, func(n ast.Node) bool {
		if call, ok := n.(*ast.CallExpr); ok {
			if mux, ok := registration(call); ok && mux == p.Mux && isPattern(call.Args[0]) {
				present = true
			}
		}
		return true
	})
	var last ast.Stmt // the last registration directly in the function body
	for _, st := range fd.Body.List {
		if es, ok := st.(*ast.ExprStmt); ok {
			if call, ok := es.X.(*ast.CallExpr); ok {
				if mux, ok := registration(call); ok && mux == p.Mux {
					last = st
				}
			}
		}
	}

	type edit struct {
		off  int
		text string
	}
	var edits []edit
	if !present {
		if last == nil {
			return nil, fmt.Errorf("%s: %s registers no route on %s as a statement of its own", p.File, p.Func, p.Mux)
		}
		start, end := tf.Offset(last.Pos()), tf.Offset(last.End())
		lineStart := bytes.LastIndexByte(src[:start], '\n') + 1
		indent := string(src[lineStart:start])
		lineEnd := bytes.IndexByte(src[end:], '\n')
		if strings.TrimSpace(indent) != "" || lineEnd < 0 {
			return nil, fmt.Errorf("%s:%d: the last route registration does not stand on a line of its own", p.File, fset.Position(last.Pos()).Line)
		}
		if rest := strings.TrimSpace(string(src[end : end+lineEnd])); rest != "" && !strings.HasPrefix(rest, "//") {
			return nil, fmt.Errorf("%s:%d: the last route registration does not stand on a line of its own", p.File, fset.Position(last.Pos()).Line)
		}
		line := fmt.Sprintf("%s%s.Handle(%q, %s.Handler())%s", indent, p.Mux, Pattern, name, nl)
		edits = append(edits, edit{end + lineEnd + 1, line})
	}
	if !imported {
		off, text := importEdit(fset, file, src, p.Import, nl)
		edits = append(edits, edit{off, text})
	}

	sort.Slice(edits, func(i, j int) bool { return edits[i].off > edits[j].off })
	out := append([]byte(nil), src...)
	for _, e := range edits {
		out = append(out[:e.off], append([]byte(e.text), out[e.off:]...)...)
	}
	return out, nil
}

// registration reports whether call is X.Handle or X.HandleFunc with a
// pattern and a handler, and returns X.
func registration(call *ast.CallExpr) (string, bool) {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok || len(call.Args) != 2 || (sel.Sel.Name != "Handle" && sel.Sel.Name != "HandleFunc") {
		return "", false
	}
	return types.ExprString(sel.X), true
}

func isPattern(e ast.Expr) bool {
	lit, ok := e.(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return false
	}
	s, err := strconv.Unquote(lit.Value)
	return err == nil && s == Pattern
}

// importName is the name the file uses for the spec package, and whether it
// already imports it. Another import named apispec is an error.
func importName(file *ast.File, importPath string) (string, bool, error) {
	for _, im := range file.Imports {
		p, _ := strconv.Unquote(im.Path.Value)
		name := path.Base(p)
		if im.Name != nil {
			name = im.Name.Name
		}
		if p == importPath {
			if name == "_" || name == "." {
				return "", false, fmt.Errorf("%s is imported as %s; the spec route needs it by name", importPath, name)
			}
			return name, true, nil
		}
		if name == pkgName {
			return "", false, fmt.Errorf("the file already imports %s as %s", p, pkgName)
		}
	}
	return pkgName, false, nil
}

// importEdit is where the spec package's import goes and its text: in sorted
// position in the parenthesized group that holds the module's own imports,
// else as a new group at the end of the last import block, else as an import
// declaration of its own after the last one (or after the package clause).
// Existing lines never change.
func importEdit(fset *token.FileSet, file *ast.File, src []byte, importPath, nl string) (int, string) {
	tf := fset.File(file.Pos())
	lineAfter := func(pos token.Pos) int { // offset just past the line holding pos
		off := tf.Offset(pos)
		if i := bytes.IndexByte(src[off:], '\n'); i >= 0 {
			return off + i + 1
		}
		return len(src)
	}
	lineStart := func(pos token.Pos) int {
		off := tf.Offset(pos)
		return bytes.LastIndexByte(src[:off], '\n') + 1
	}
	module := strings.TrimSuffix(importPath, "/"+strip.SpecDir)
	quoted := strconv.Quote(importPath)

	var last *ast.GenDecl
	for _, d := range file.Decls {
		if g, ok := d.(*ast.GenDecl); ok && g.Tok == token.IMPORT {
			last = g
			if !g.Lparen.IsValid() {
				continue
			}
			// Split the block into groups at blank lines, as gofmt does.
			var groups [][]*ast.ImportSpec
			prevLine := 0
			for _, s := range g.Specs {
				is := s.(*ast.ImportSpec)
				line := fset.Position(is.Pos()).Line
				if len(groups) == 0 || line > prevLine+1 {
					groups = append(groups, nil)
				}
				groups[len(groups)-1] = append(groups[len(groups)-1], is)
				prevLine = fset.Position(is.End()).Line
			}
			for _, grp := range groups {
				own := false
				for _, is := range grp {
					p, _ := strconv.Unquote(is.Path.Value)
					own = own || p == module || strings.HasPrefix(p, module+"/")
				}
				if !own {
					continue
				}
				indent := string(src[lineStart(grp[0].Pos()):tf.Offset(grp[0].Pos())])
				for _, is := range grp {
					if p, _ := strconv.Unquote(is.Path.Value); p > importPath {
						return lineStart(is.Pos()), indent + quoted + nl
					}
				}
				return lineAfter(grp[len(grp)-1].End()), indent + quoted + nl
			}
		}
	}
	switch {
	case last == nil:
		return lineAfter(file.Name.End()), nl + "import " + quoted + nl
	case last.Lparen.IsValid() && len(last.Specs) > 0:
		spec := last.Specs[len(last.Specs)-1]
		indent := string(src[lineStart(spec.Pos()):tf.Offset(spec.Pos())])
		return lineAfter(spec.End()), nl + indent + quoted + nl
	default:
		return lineAfter(last.End()), "import " + quoted + nl
	}
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
